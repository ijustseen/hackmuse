import type { JudgeId, VotingJudgeId } from "./judges";
import type { CriterionId } from "./rubric";

export interface DebateLine {
  speaker: JudgeId;
  /** The judge this line answers, if any (guides the writing; not drawn). */
  replyTo: JudgeId | null;
  /** One-word delivery cue ("skeptical", "excited"…). */
  cue: string;
  text: string;
}

export interface CriterionScore {
  score: number;
  note: string;
}

export interface Debate {
  idea: string;
  title: string;
  lines: DebateLine[];
  scores: Record<CriterionId, CriterionScore>;
  votes: Record<VotingJudgeId, number>;
  overall: number;
  verdict: string;
  strengths: string[];
  risks: string[];
  /** "gemma" when generated by the model, "demo" when no API key is configured. */
  source: "gemma" | "demo";
  model: string;
}

/** NDJSON events streamed by POST /api/debate, one per line. */
export type StreamEvent =
  | { type: "meta"; source: Debate["source"]; model: string }
  | { type: "title"; title: string }
  | { type: "line"; line: DebateLine }
  | { type: "debate"; debate: Debate }
  | { type: "error"; message: string };
